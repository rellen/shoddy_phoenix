defmodule ShoddyPhoenix do
  @moduledoc """
  Small functions for tasks that occur frequently in Phoenix code.

  ShoddyPhoenix is the companion library of
  [Shoddy](https://github.com/rellen/shoddy). Shoddy uses only the standard
  library of Elixir. ShoddyPhoenix contains the functions that need Phoenix.
  Thus a project that does not use Phoenix can use Shoddy, and it does not get
  Phoenix as a dependency.

  ShoddyPhoenix obeys the conventions of Shoddy. For example, the first
  argument of each function is the value that the function operates on. Thus
  each function can be a step of a pipeline.
  """
end
